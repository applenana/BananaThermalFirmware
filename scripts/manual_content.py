def p(text): return ("p", text)
def h(text): return ("h", text)
def s(title, result): return ("s", title, result)
def n(label, text): return ("n", label, text)
def t(headers, rows, widths): return ("t", headers, rows, widths)
def i(name, caption, width=6.7, crop=None): return ("i", name, caption, width, crop)
def l(label, target): return ("l", label, target)
def page(title, lead, *blocks, chapter="设备操作"):
    return dict(title=title, lead=lead, blocks=list(blocks), chapter=chapter)


